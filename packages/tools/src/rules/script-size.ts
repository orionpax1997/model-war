/**
 * 脚本体积上限规则(纯规则层):一段**编译后产物**的字节数 → 一组违规(没有位置)。
 * **不碰文件系统**,也不读时钟与环境:字节数由调用方交给判定链,本规则只拿那一个数与一个上限比。
 *
 * ── 它封的是什么:运行时体量对应的控制流计数盲区,不是源码行数 ──────────────────
 * 预算的成本模型按**控制流计数**计量(格数、步数、累计计数那几类量),于是有两类体量对它不可见:
 * **直线代码不计数**——它不进任何计数器,却仍然逐格执行;而**每格的工作量会放大**——循环体里
 * 多做一件事,成本就是格数乘以那件事。所以一份把循环拆成直线代码的脚本,指标漂亮而运行时体量翻倍,
 * 计数这一层看不见它。本规则是那层看不见的东西的兜底:量的不是行数,是**产物的字节数**。
 *
 * ── 为什么量编译产物而不是原始 TS ──────────────────────────────────────────────
 * 3000 行类型注解编译后可能只剩几百字节。量原始源码会把「写了很多类型」误判成运行时风险,
 * 而那条风险并不存在。规则跑在编译产物上这件事对四条规则是统一的(spec《规则跑在编译产物上》),
 * 本规则只把它的后果落到一行:字节数从共享上下文里取,不由本规则去读文件。
 *
 * ── 边界三态:低于上限通过、**恰好等于上限通过**、高于上限违规 ─────────────────
 * 「恰好等于」按不超过判违规(`byteLength > maxBytes`),所以判据是一句比较而不是一个差值阈值。
 *
 * ── 检查时机:每轮迭代都查,迭代期只提示、冻结期才拦 ──────────────────────────────
 * 体积超标常常要到后几轮功能写完才成为决定性因素,而每轮都拦会把模型逼向**压体积**;
 * 最自然的压法是把循环拆成直线代码——恰好是本规则要封的盲区的另一面。所以分两级:
 * 同一份判据、同一句诊断,只有 `blocking` 那一维不同。两级由**上下文里的 `phase` 显式区分**
 * (判定链从入口的 `--phase` 一路传下来),不靠猜「现在大概是哪一轮」。
 *
 * ── 那句「改算法,不要拆直线代码」是规则的一部分 ────────────────────────────────
 * 它不是文案润色:它是把「为什么超标要往算法上改、而不是往直线代码上改」直接交给模型的那半条信息。
 * 少了它,模型收到「体积超标」这一条反馈时最省力的动作就是把循环摊开——而那会让指标更好看、体量更大。
 * **提示路径与拦截路径都带这一句**:提示期正是模型最容易随手拆循环的时候。
 *
 * ── 违规没有位置,而 `blocking` 是这里唯一分两档的那一维 ────────────────────────
 * 本级不是 AST 规则,`line` / `column` 恒为 `null`——硬给一个 `1:1` 只会让「这个位置是猜的」
 * 消失在数据里。排序契约把无位置的违规落在末尾,见 `script-lint.ts` 的 `compareViolations`。
 *
 * ── 上限是入参,校验器不给默认值 ────────────────────────────────────────────────
 * 取值在规则集文件里,那是生成管线(E)的交付物、现在不存在;写一个默认值就是给一个未定值编答案。
 * 上限在**共享上下文**里而不是各条规则各带一个参数:另外三条 AST 规则拿不到它的补偿,
 * 却要为它各多带一个自己根本不看的参数(`rules/script-lint.ts` 有完整的一段)。
 */

import type {
  ScriptLintContext,
  ScriptLintPhase,
  ScriptLintStage,
  ScriptViolation,
} from "./script-lint.ts";

/**
 * 规则层自己的两个旋钮,形状与 `ScriptLintContext` 上对应的两项一致。
 * 库层直接调本规则时用它;判定链那一侧由 `scriptSizeStage` 从上下文里取,不必重复问。
 */
export type ScriptSizeOptions = {
  /** 体积上限,字节。比较是「超过才算」,所以恰好等于上限通过。 */
  readonly maxBytes: number;
  /** 迭代期只提示、冻结期拦。 */
  readonly phase: ScriptLintPhase;
};

/** 那半条规则信息。**两档都要带**,所以它是常量而不是某一档才拼的片段。 */
const REFACTOR_ADVICE =
  "改算法,不要拆直线代码:把循环摊成直线代码不会让它变小,只会让每格的工作量放大," +
  "而那一项正是预算的成本模型看不见的——要压的是重复的计算和分支,不是行数。";

/**
 * 一条面向模型的诊断:说清**当前多少字节、上限多少、超出多少**,再说清往哪个方向改。
 *
 * 超出多少字节是模型判断「要缩多少」的唯一依据,所以它在两档里都写死;两档之间差的是
 * 「拦住还是先放着」和那句话的语气,不是数字。
 */
const sizeMessage = (
  byteLength: number,
  maxBytes: number,
  over: number,
  phase: ScriptLintPhase,
): string => {
  const verdict =
    phase === "freeze"
      ? "冻结期不接受这份产物,它必须缩到上限之内;"
      : "这一轮只提示、不拦截,但它会随后续功能继续涨,别留到最后才缩;";
  return `脚本体积 ${byteLength} 字节,比上限 ${maxBytes} 字节多出 ${over} 字节。${verdict}${REFACTOR_ADVICE}`;
};

/**
 * 规则层的对外缝:字节数 → 一组违规(空数组 = 在上限之内)。
 *
 * 没有「超了但先不报」这个形态:超了就一定有一条违规,拦不拦是 `blocking` 那一维的事。
 * 少报一次会让模型在冻结期第一次听见这件事,而那时预算已经花完了。
 */
export const scriptSizeViolations = (
  byteLength: number,
  options: ScriptSizeOptions,
): readonly ScriptViolation[] => {
  const { maxBytes, phase } = options;
  if (byteLength <= maxBytes) {
    return [];
  }
  return [
    {
      rule: "script-size",
      message: sizeMessage(byteLength, maxBytes, byteLength - maxBytes, phase),
      // 不是 AST 规则,没有位置可言。
      line: null,
      column: null,
      // 唯一分两档的那一维:迭代期提示、冻结期拦。退出码与面向模型层的排版都按它分流。
      blocking: phase === "freeze",
    },
  ];
};

/**
 * 判定链上的体积级(五级里的最后一级,顺序是裁决,见 `validate/pipeline.ts`)。
 *
 * 它吃的是共享上下文里的 `byteLength` 与 `maxBytes`,**不重复解析、不碰 AST**——
 * 另外三条 AST 规则的纯函数也因此不必多带一个字节数参数。
 * 上下文里没有解析结果时(`parsed` 为 undefined,语法失败那条路径)照样判:体积是字节数的事实,
 * 与语法能不能解析无关;那条路径上判定链返回的是「解析失败独占」的结果,本级根本不会被问到。
 */
export const scriptSizeStage: ScriptLintStage = (context: ScriptLintContext) =>
  scriptSizeViolations(context.byteLength, { maxBytes: context.maxBytes, phase: context.phase });
