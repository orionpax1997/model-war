/**
 * 一件生成物的形状。刻意只有一个文件、三个字段:它是注册表与漂移检查之间唯一的契约,
 * 加字段就是加契约,而契约一多,「新增生成物是往表里加一行」这条纪律就守不住了。
 *
 * `id` 与 `path` 都不是给人看的注释:漂移检查按 `path` 做 git 路径限定与状态检查,
 * 报告里按 `id` 指认是哪一件——两者都要求它们是**稳定的串**,不随真源内容变化。
 */
export type GeneratedArtifact = {
  /** 标识。报告与将来多件生成物之间的区分靠它;要进生成物自身的生成头注释。 */
  readonly id: string;
  /** 产出位置,仓库根起的**相对路径**。用相对路径是因为漂移检查要在 git 的路径限定里用同一个串。 */
  readonly path: string;
  /** 生产函数:真源 → 生成物全文(末尾带换行)。纯函数,不碰文件系统、不看时钟。 */
  readonly produce: () => string;
};
