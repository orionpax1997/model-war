/**
 * 一件生成物的形状。刻意只有一个文件、**两种形态**:它是注册表与生成器/漂移检查之间唯一的契约,
 * 加字段就是加契约,而契约一多,「新增生成物是往表里加一行」这条纪律就守不住了。
 *
 * ── 为什么形态写在类型上,而不是让人去猜 ──
 *
 * `form` 是判别字段,两种形态的差别在编译期就得看得见。改成「靠某个字段在不在来判断」的话,
 * 每加一种形态,每个消费点就要多写一个「忘了写就默默按另一种处理」的守卫——而守卫漏一处的后果
 * 不是报错,是**安静地按错的形态处理**:生成器会把正文填到错的位置,漂移检查会去比错的东西,
 * 两条路都还打印出一句人话,报告读起来完全正常。
 *
 * 两种形态的差别只在 `produce` 返回什么:整文件形态返回全文,区块形态返回「标记 + 正文」。
 * 身份(`id` / `path`)与落点一字不差,所以骨架(生成器入口、漂移门禁的两刀 git 判定)对两者相同。
 *
 * `id`、`path` 与区块形态的 `marker` 都不是给人看的注释,而是**定位用的稳定串**:漂移检查按
 * `path` 做 git 路径限定与状态检查,按 `marker` 抽出要逐字节比的那一段,报告里按 `id` 指认是哪一件
 * ——三者都要求它们**不随真源内容变化**。`marker` 尤其如此:它一变,被比的那一段就换了地方,
 * 而检查还是绿的。
 *
 * ── 「纯函数」:不看时钟、不写文件,而「读真源」不在禁止之列 ──
 *
 * 两条约束各防一种漂移:**不看时钟**防的是「同样的真源两次跑出两段字节」,那一类漂移连逐字节
 * 比都对不上;**不写文件**防的是「生产函数顺手改了别的东西」,那让检查的判决与被检查物纠缠在一起。
 *
 * 「读真源」不同:它正是**输出只由真源决定**这条性质的兑现,不是它的反面。真源是代码时走
 * `import` 编译产物(`@model-war/schema`,所以生成器要有 `tsc -b` 前置),真源是数据文件时读那个文件
 * (`rulesets/v1.json`)。两种真源都需要漂移检查**在检查当时**看到真源的现状,所以两边都由检查与
 * 生成器共用的同一个生产函数去取——共用是关键:分开取,「检查比的那段」与「生成器写的那段」就
 * 可能不是同一口径,而检查会一直绿。
 */

/** 两种形态共有的身份与落点。形态差异不在这里,只在 `produce` 返回的东西上。 */
type ArtifactIdentity = {
  /** 标识。报告与将来多件生成物之间的区分靠它;要进生成物自身的生成头注释。 */
  readonly id: string;
  /** 产出位置,仓库根起的**相对路径**。用相对路径是因为漂移检查要在 git 的路径限定里用同一个串。 */
  readonly path: string;
};

/**
 * 定界标记:区块的首行与末行各一条,**各自独占一行**(前后不带任何东西)。
 *
 * 它是稳定的串:默认形态由 `sectionMarker(id)` 从 `id` 拼出,不带行号、不带内容摘要、不带时间戳。
 * 后三者都会随内容与位置变化,而「按标记抽区块」正是靠标记不随内容变才成立。
 *
 * 取值自由(生产函数可以给别的形状),但「独占一行」与「只出现一次」两条是抽得出来、抽得准的前提,
 * 由 `section.ts` 那份机械兑现。
 */
export type SectionMarker = {
  readonly begin: string;
  readonly end: string;
};

/** 区块形态的真源产出:**标记 + 正文**。正文**不含**那两行定界标记,末尾带换行。 */
export type Section = {
  readonly marker: SectionMarker;
  readonly content: string;
};

/** 整文件形态:目标文件从第一行到最后一行都是生成物,整份逐字节比。 */
export type WholeFileArtifact = ArtifactIdentity & {
  readonly form: "whole-file";
  /** 生产函数:真源 → 生成物全文(末尾带换行)。不看时钟、不写文件;真源是数据文件时读它(见头注)。 */
  readonly produce: () => string;
};

/**
 * 区块形态:目标文件里两行定界标记之间是生成物,区块外的散文是人的,**不比**。
 *
 * 它服务的对象是散文占七成篇幅的混合文件(规则文档那一类):逐字节比整份会把散文也锁死,
 * 而锁死散文等于让人不敢改文档。代价是标记成了新的绕过面——所以抽不出区块按漂移报,
 * 不按「无事可查」跳过(判定在 `run-drift-gate.ts`,机械在 `section.ts`)。
 *
 * 生产函数的纪律与整文件形态同源,只是落点换了地方:①生成头注释仍给**三件套**(勿手改 /
 * 真源在哪 / 为什么规则层读的是生成物),`emit.ts` 的 `generatedHeader` 是它的模板;②排版零件
 * 只有 `emit.ts` 那一份(`PRINT_WIDTH` 复刻 `.oxfmtrc.json`),正文要过格式化门禁靠的是这个,
 * 不是另起一套宽度判断;③**判据随真源走、不在正文里复述**——判据抄一份就会漂移,而漂移的注释
 * 比没有注释更坏。①②③里只有「落点」从整份文件换成了两行标记之间那一段。
 */
export type SectionArtifact = ArtifactIdentity & {
  readonly form: "section";
  /** 生产函数:真源 → 标记 + 正文。不看时钟、不写文件;真源是数据文件时读它(见头注)。 */
  readonly produce: () => Section;
};

/** 一件生成物。两种形态的并集,靠 `form` 分派;新增生成物只往注册表里加一行。 */
export type GeneratedArtifact = WholeFileArtifact | SectionArtifact;
