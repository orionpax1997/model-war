/**
 * 宿主工具的一次**结果**:工具调用的回执,不是一个跨进程的字节协议。
 *
 * ── 它以前叫 `ToolResponse`,那是 fd 3 通道的响应体 ──
 *
 * 旧形状是「一行 JSON 一请求、一行 JSON 一响应」的响应端:沙箱里的薄壳按手写的键序与七条
 * 转义表去切字段,所以键序、转义表、`stderr` 居末都是**协议**。那条通道已整套删除(票 03,
 * 模型**没有那条路径**,而不是「敲不到别的路径」),
 * 于是这里只剩一个**宿主内**的对象:dispatcher 交回、执行器读、两个服务产出。
 *
 * ── 为什么仍然不是「成功/失败」两态 ──
 *
 * 三格各说一件事,而不是把三件事压成一个布尔:
 *
 * - `stdout` / `stderr`:模型读到的两路文本(观测渲染按这两格走,`history.ts` 的
 *   `renderObservation`)。拒绝的文案也走 `stderr`——它是**给模型读的那句话**,载体换了
 *   (从「伪造一条命令的 stderr」换成「一条被拒的工具调用的输出」),字不换。
 * - `exitCode`:观测里那个数。被拒的那一次没有进程跑过,这个数沿用「非零 = 这次不成功」的
 *   历史口径。
 * - `isError`:这一次**工具调用**本身失败(配额用完、会话到点、名字不认识、参数误用、服务抛错),
 *   与「命令跑了但非零退出」是两件事。旧世界把两者混成一个伪造的退出码;新世界由这一格说清楚,
 *   读它的人(执行器 / loop)不用去猜文案。
 *
 * `result` 直接复用档案契约里的 `ArchiveStepResult`:它俩是同一件事(进了 `steps[i].result`
 * 的那一格),在 schema 里再抄一份只是给同一个形状开第二个家。
 *
 * ── 这一格不落档案 ──
 *
 * `steps[i]` 的形状是票 01 定死的契约(`ArchiveStep`),它没有 `isError` 这一位;这个标记活到
 * loop 决定「这一步算不算收工」为止——**被拒的 `finish` 不是收工**。
 */

import type { ArchiveStepResult } from "./archive-meta.js";

/** 一次工具调用的结果。只由宿主产出,不经任何序列化。 */
export type ToolOutcome = {
  /** 观测里那个数(见头注:被拒时它不是任何进程的退出码)。 */
  readonly exitCode: number;
  /** 模型看到的第一路输出。 */
  readonly stdout: string;
  /** 模型看到的第二路输出(拒绝文案也走这里,它是模型读的那句话)。 */
  readonly stderr: string;
  /** 结果侧派生视图(与档案 `steps[i].result` 同一格);没有可归纳的东西时缺席。 */
  readonly result?: ArchiveStepResult;
  /**
   * 这一次**工具调用**失败(拒绝,或服务自己抛错),不是「命令非零退出」。
   *
   * 缺席 = 这次调用被受理并跑完了(命令自己可能失败,那是 `exitCode` 的事)。
   */
  readonly isError?: boolean;
};
