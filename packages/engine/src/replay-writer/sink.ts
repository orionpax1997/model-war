/**
 * 输出 sink:回放写出的唯一出口。
 *
 * ── 为什么不是一个文件路径 ──
 *
 * hld §2.2.8 把磁盘 I/O 排除在 engine 之外。写成 `writeLine(path, line)` 就等于把这个包
 * 重新绑到文件系统上:测试要先造目录、上层要传路径、而「写到哪」这件事本就不属于结算。
 * 收成一个回调之后,本包手里始终只有**一行字符串**,而「落到哪个文件、要不要压缩、要不要先
 * 校验 meta 再落盘」全部留在 02b 那一格——它本来就该在那里,退出码也才映射得出来。
 *
 * 方法名是 `write` 而不是 `appendLine`:它写的是**一行**,换行是 sink 自己的事(它可能写进一个
 * 已经在别处被拼好的字符串里)。让本包去拼 `\n` 就等于假定 sink 一定是文本文件,而 `02b` 若要把
 * 行喂给一个 JSONL 校验器,那多出来的一个换行就得被去掉。
 */

export type TickSink = {
  readonly write: (line: string) => void;
};
