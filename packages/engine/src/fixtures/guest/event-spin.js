// 沙箱夹具(票 07 双计数之「纯计算死循环」那一臂):一个有回边与调用、零 API 调用的死循环。
//
// 为什么它证明的是**控制流事件计数**这一轨:quickjs-wasi 的 `interruptHandler` 按控制流事件
// (循环回边 / 调用 / 返回)计数,每 5000 次触发一次回调——直线代码零计量(那个盲区由脚本体积
// 上限封)。本夹具既自旋(回边)又调一个轻量函数(调用事件),所以它一定会把本轨顶到限。
//
// 为什么它**不**会被 API 调用计数抓到:它一个注入 API 函数都不调,所以宿主收到的 `apiCalls`
// 是 0。截停它的只可能是事件计数轨——这正是两条轨互为盲区、必须成对的证据。
//
// 零分配:循环体只动整数,不 push、不建对象,所以也不会掉进内存判据那一轨。
//
// 确定性:死循环本身不产生任何输出;能观测到的唯一事实是「它被宿主截停」。

function spin(n) {
  let acc = 0;
  for (let i = 0; i < n; i++) {
    acc = (acc + 1) % 7;
  }
  return acc;
}

function loop() {
  for (;;) {
    spin(1000);
  }
}
